"""Build results/results_summary.md (paste-ready markdown tables) from the CSVs."""
from __future__ import annotations

from pathlib import Path

import pandas as pd

from .config import Config
from .mobility import stationary_blockage


def _read(out: Path, name: str) -> pd.DataFrame | None:
    p = out / "data" / f"{name}.csv"
    return pd.read_csv(p) if p.exists() else None


def _pm(m: float, ci: float, nd: int = 1) -> str:
    return f"{m:.{nd}f} ± {ci:.{nd}f}"


def _policy_md(s: pd.DataFrame) -> str:
    lines = ["| Scheme | Avg throughput (Mbps) | Outage (%) | Switches / 300 s | Time on Li-Fi (%) |",
             "|---|---:|---:|---:|---:|"]
    for _, r in s.iterrows():
        lines.append(f"| {r.policy} | {_pm(r.avg_mean, r.avg_ci95)} | {_pm(r.outage_mean, r.outage_ci95, 2)} "
                     f"| {_pm(r.switches_mean, r.switches_ci95)} | {_pm(r.lifi_share_mean, r.lifi_share_ci95)} |")
    return "\n".join(lines)


def _findings(out: Path, cfg: Config) -> list[str]:
    """Plain-language findings, each computed from the CSVs."""
    f = []
    s6, s4 = _read(out, "E6_statistics_summary"), _read(out, "E4_blockage_sweep")
    s5, s7 = _read(out, "E5_hysteresis_sweep"), _read(out, "E7_policy_comparison")
    if s6 is not None:
        g = {r.policy: r for _, r in s6.iterrows()}
        h = g[[k for k in g if k.startswith("Hysteresis")][0]]
        li, wi = g["Li-Fi only"], g["Wi-Fi only"]
        f.append(f"Hybrid delivers {h.avg_mean/wi.avg_mean:.1f}x the Wi-Fi-only throughput "
                 f"({h.avg_mean:.1f} vs {wi.avg_mean:.1f} Mbps) but {li.avg_mean-h.avg_mean:.1f} Mbps less than "
                 f"Li-Fi only, while cutting outage from {li.outage_mean:.2f}% to {h.outage_mean:.2f}%.")
        f.append("Wi-Fi only is a constant 120 Mbps with 0% outage in every run: its SNR is always above the "
                 "spectral-efficiency cap (see README, Known issues). All hybrid outage comes from the "
                 f"{cfg.switch_cost_steps*cfg.dt:g} s handover penalty, not from a link failing.")
    if s4 is not None:
        hy = s4[s4.policy == "Hybrid"].sort_values("p_block_in")
        li = s4[s4.policy == "Li-Fi only"].sort_values("p_block_in")
        diff = hy.outage_pct.values - li.outage_pct.values
        x = 100 * hy.blocked_frac_theory.values
        idx = [i for i in range(1, len(diff)) if diff[i-1] > 0 >= diff[i]]
        if idx:
            i = idx[0]
            xc = x[i-1] + (x[i]-x[i-1]) * diff[i-1] / (diff[i-1]-diff[i])
            f.append(f"Hybrid beats Li-Fi only on outage only when Li-Fi is blocked more than about "
                     f"{xc:.0f}% of the time (E4); with little blockage the handover penalty makes the hybrid worse "
                     f"({hy.outage_pct.iloc[0]:.2f}% vs {li.outage_pct.iloc[0]:.2f}% with no blockage).")
    if s7 is not None:
        g = {r.policy: r for _, r in s7.iterrows()}
        h = g[[k for k in g if k.startswith("Hysteresis")][0]]
        singles = [g[k] for k in g if k.startswith("Single")]
        f.append("Hysteresis gives fewer switches (" + f"{h.switches_mean:.0f}" + " vs " +
                 " / ".join(f"{r.switches_mean:.0f}" for r in singles) +
                 " for single thresholds) and the lowest hybrid outage, but not the highest throughput "
                 f"(single 10 dB threshold: {singles[0].avg_mean:.1f} Mbps vs {h.avg_mean:.1f}) (E7).")
    if s5 is not None:
        ch = s5[(s5.thr_up_db == cfg.thr_hi_db) & (s5.thr_down_db == cfg.thr_lo_db)].iloc[0]
        bt = s5.loc[s5.avg_mbps.idxmax()]
        f.append(f"The chosen {cfg.thr_hi_db:g}/{cfg.thr_lo_db:g} dB thresholds are not throughput-optimal: "
                 f"{bt.thr_up_db:g}/{bt.thr_down_db:g} dB gives {bt.avg_mbps:.1f} vs {ch.avg_mbps:.1f} Mbps (E5). "
                 "Li-Fi already beats 120 Mbps Wi-Fi above ~4 dB SNR in this model, so high thresholds leave "
                 "usable Li-Fi unused. Thresholds were NOT retuned for the headline table.")
    f.append("Bandwidth trades coverage for peak rate: 10 MHz covers most of the room at 15 dB but caps rate "
             "at 60 Mbps; 100 MHz covers ~44% (E3). Corner (0,0) is outside the 60 deg FOV by default.")
    s8 = _read(out, "E8_led_grid_coverage")
    if s8 is not None:
        f.append(f"Four LEDs reach {s8.coverage_pct.iloc[1]:.0f}% coverage only with 4x the optical power; at equal "
                 f"total power coverage drops to {s8.coverage_pct.iloc[2]:.1f}% (SNR scales with power squared) (E8).")
    return f


def write_summary(cfg: Config, out: Path, quick: bool = False) -> Path:
    out = Path(out)
    md = ["# Results summary", "",
          "Generated by `python -m lifi run --all`. All numbers are computed, not tuned. "
          "± values are 95% confidence-interval half-widths (Student t) over independent seeds.",
          ""]
    if quick:
        md += ["> **QUICK MODE**: fewer seeds / bits / grid points. Use the full run for reporting.", ""]
    md += ["## Key findings", ""] + [f"- {x}" for x in _findings(out, cfg)] + [""]

    s6 = _read(out, "E6_statistics_summary")
    if s6 is not None:
        n = int(s6.n_seeds.iloc[0])
        md += [f"## 1. Headline results (E6, {n} independent seeds)", "",
               f"Room {cfg.room:g}×{cfg.room:g} m, one LED, {cfg.sim_time:g} s per run, "
               f"blockage p_in={cfg.p_block_in:g}, p_out={cfg.p_block_out:g} "
               f"(blocked {100*stationary_blockage(cfg.p_block_in, cfg.p_block_out):.1f}% of time in the long run), "
               f"hysteresis {cfg.thr_hi_db:g}/{cfg.thr_lo_db:g} dB, {cfg.switch_cost_steps*cfg.dt:g} s outage per switch.",
               "", _policy_md(s6), ""]
    b0 = _read(out, "E0_baseline_seed42")
    if b0 is not None:
        md += ["Single-run prototype baseline (seed 42, regression reference): " +
               "; ".join(f"{r.scheme} {r.avg_mbps:.1f} Mbps / {r.outage_pct:.2f}% outage"
                         for _, r in b0.iterrows()) +
               f"; hybrid switches {int(b0.switches.iloc[-1])}, time on Li-Fi {b0.lifi_share_pct.iloc[-1]:.1f}%. "
               "One run is a single sample; quote the E6 table above.", ""]

    s7 = _read(out, "E7_policy_comparison")
    if s7 is not None:
        md += ["## 2. Policy comparison (E7, same seeds as E6)", "",
               "Single-threshold = switch at one SNR level (no hysteresis). "
               "Ideal = best link each step with zero switching cost (an upper bound, not a real policy).",
               "", _policy_md(s7), ""]

    s4 = _read(out, "E4_blockage_sweep")
    if s4 is not None:
        md += ["## 3. Blockage sweep (E4)", "",
               "| Blocked time (%) | Wi-Fi only (Mbps / outage %) | Li-Fi only (Mbps / outage %) | Hybrid (Mbps / outage %) | Hybrid switches |",
               "|---:|---:|---:|---:|---:|"]
        for p, d in s4.groupby("p_block_in", sort=True):
            g = {r.policy: r for _, r in d.iterrows()}
            md.append(f"| {100*d.blocked_frac_theory.iloc[0]:.1f} | "
                      + " | ".join(f"{g[k].avg_mbps:.1f} / {g[k].outage_pct:.2f}"
                                   for k in ("Wi-Fi only", "Li-Fi only", "Hybrid"))
                      + f" | {g['Hybrid'].switches:.1f} |")
        md.append("")

    s5 = _read(out, "E5_hysteresis_sweep")
    if s5 is not None:
        ch = s5[(s5.thr_up_db == cfg.thr_hi_db) & (s5.thr_down_db == cfg.thr_lo_db)].iloc[0]
        bt = s5.loc[s5.avg_mbps.idxmax()]
        bo = s5.loc[s5.outage_pct.idxmin()]
        bs = s5.loc[s5.switches.idxmin()]
        md += ["## 4. Hysteresis threshold sweep (E5)", "",
               "| Setting (up/down dB) | Avg throughput (Mbps) | Outage (%) | Switches |",
               "|---|---:|---:|---:|"]
        for lab, r in ((f"Chosen {ch.thr_up_db:g}/{ch.thr_down_db:g}", ch),
                       (f"Max throughput {bt.thr_up_db:g}/{bt.thr_down_db:g}", bt),
                       (f"Min outage {bo.thr_up_db:g}/{bo.thr_down_db:g}", bo),
                       (f"Fewest switches {bs.thr_up_db:g}/{bs.thr_down_db:g}", bs)):
            md.append(f"| {lab} | {r.avg_mbps:.1f} | {r.outage_pct:.2f} | {r.switches:.1f} |")
        md += ["", f"Grid: up {s5.thr_up_db.min():g}–{s5.thr_up_db.max():g} dB, down "
               f"{s5.thr_down_db.min():g}–{s5.thr_down_db.max():g} dB (down < up), "
               f"{int(s5.n_seeds.iloc[0])} seeds per point.", ""]

    s3 = _read(out, "E3_parameter_sweeps")
    if s3 is not None:
        md += ["## 5. Single-LED parameter sweeps (E3)", "",
               f"Coverage = % of room grid with SNR ≥ {cfg.coverage_snr_db:g} dB. Corner = (0, 0); "
               "'no LOS' means the corner is outside the receiver FOV.", "",
               "| Parameter | Range | Coverage range (%) | Best value (coverage) | Default (coverage) | Corner SNR at default (dB) |",
               "|---|---|---|---|---|---:|"]
        for prm, d in s3.groupby("parameter", sort=False):
            b = d.loc[d.coverage_pct.idxmax()]
            df_ = d[d.is_default]
            dv = f"{df_.value.iloc[0]:g} ({df_.coverage_pct.iloc[0]:.1f})" if len(df_) else "-"
            cs = df_.corner_snr_db.iloc[0] if len(df_) else float("nan")
            md.append(f"| {d.unit_label.iloc[0]} | {d.value.min():g}–{d.value.max():g} | "
                      f"{d.coverage_pct.min():.1f}–{d.coverage_pct.max():.1f} | {b.value:g} ({b.coverage_pct:.1f}) | "
                      f"{dv} | {'no LOS' if pd.isna(cs) else f'{cs:.1f}'} |")
        md.append("")

    s2 = _read(out, "E2_ber_monte_carlo")
    if s2 is not None:
        ok = s2[s2.bit_errors >= 100]
        rel = (ok.ber_mc - ok.ber_theory).abs() / ok.ber_theory
        md += ["## 6. BER validation (E2)", "",
               "| Scheme | SNR points with ≥100 errors | Max relative error MC vs theory |",
               "|---|---:|---:|"]
        for sch, d in ok.assign(rel=rel).groupby("scheme", sort=False):
            md.append(f"| {sch} | {len(d)} | {100*d.rel.max():.1f}% |")
        md.append("")

    s8 = _read(out, "E8_led_grid_coverage")
    if s8 is not None:
        md += ["## 7. Multi-LED coverage (E8, stretch)", "",
               "Strongest-LED association, **no inter-cell interference** (optimistic).", "",
               "| Layout | Total optical power (W) | Coverage (%) | Median SNR (dB) |",
               "|---|---:|---:|---:|"]
        for _, r in s8.iterrows():
            md.append(f"| {r.case} | {r.p_total_w:g} | {r.coverage_pct:.1f} | {r.snr_median_db:.1f} |")
        md.append("")

    s1 = _read(out, "S1_fix_flag_sensitivity")
    if s1 is not None:
        md += ["## 8. Sensitivity to the optional fixes (S1, not used for headline numbers)", "",
               "Each row turns ONE fix flag on (see README, Known issues). Mean over the same seeds as E6.", "",
               "| Variant | Wi-Fi only (Mbps) | Li-Fi only (Mbps / outage %) | Hysteresis hybrid (Mbps / outage %) | Ideal bound (Mbps) |",
               "|---|---:|---:|---:|---:|"]
        for v, d in s1.groupby("variant", sort=False):
            g = {("Hyst" if r.policy.startswith("Hysteresis") else r.policy): r for _, r in d.iterrows()}
            md.append(f"| {v} | {g['Wi-Fi only'].avg_mean:.1f} | {g['Li-Fi only'].avg_mean:.1f} / "
                      f"{g['Li-Fi only'].outage_mean:.2f} | {g['Hyst'].avg_mean:.1f} / {g['Hyst'].outage_mean:.2f} | "
                      f"{g['Ideal (upper bound)'].avg_mean:.1f} |")
        md.append("")

    p = out / "results_summary.md"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("\n".join(md))
    return p
